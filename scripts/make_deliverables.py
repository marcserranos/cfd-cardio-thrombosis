"""We write the files for SerranoSanzMarc.zip (main Aula Global upload).

1. Case_001.seg.nrrd     LA segmentation (Marc's Slicer segmentation, cleaned: holes filled,
                         islands removed, device voxels excluded), same grid/header as the CT.
2. Case_001_LA_surface.stl   processed LA surface (Marc's Meshmixer mesh, cleaned, Z-aligned, mm)
3. Case_001_LA_volume.bdf    tetrahedral volume mesh (Gmsh + Netgen, < 500k elements, mm, Z-aligned)
4. Case_001_device.stl       WATCHMAN-type occluder wireframe (CT threshold), RAS mm like Slicer exports
"""
import os, shutil
import numpy as np
import nrrd
from scipy import ndimage as ndi
from skimage import measure
import trimesh

SP = os.environ["SP"]
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "deliverables", "SerranoSanzMarc")
os.makedirs(OUT, exist_ok=True)

meta = np.load(f"{SP}/ct_meta.npy")
sp, org = meta[:3], meta[3:]

# ---- 1. segmentation ----
seg, hdr = nrrd.read(f"{SP}/in/Segmentation.seg.nrrd")
dev = np.load(f"{SP}/device.npy")
m = seg > 0
m = m & ~ndi.binary_dilation(dev, iterations=1)  # we keep the device out of the LA
lab, n = ndi.label(m)
sz = np.bincount(lab.ravel()); sz[0] = 0
m = lab == np.argmax(sz)  # we drop small islands
m = ndi.binary_fill_holes(m)  # we fill the pinholes inside the blood pool
print("LA segmentation volume mL:", round(m.sum() * sp.prod() / 1000, 1), "changed voxels:", int((m != (seg > 0)).sum()))
hdr["Segment0_Name"] = "LeftAtrium"
hdr["Segment0_NameAutoGenerated"] = "0"
nrrd.write(os.path.join(OUT, "Case_001.seg.nrrd"), m.astype(np.uint8), hdr, compression_level=6)

# ---- 4. device wireframe STL (RAS, like the Slicer exports used in class) ----
idx = np.argwhere(dev)
lo, hi = idx.min(0) - 2, idx.max(0) + 3
sub = dev[lo[0]:hi[0], lo[1]:hi[1], lo[2]:hi[2]].astype(np.float32)
sub = ndi.gaussian_filter(sub, 0.5)  # we smooth the voxel staircase a little
v, f, _, _ = measure.marching_cubes(sub, 0.5, spacing=tuple(sp))
v = v + org + lo * sp  # LPS mm
v_ras = v * np.array([-1.0, -1.0, 1.0])
d = trimesh.Trimesh(v_ras, f[:, ::-1], process=True)  # flipping x and y keeps handedness, we reorder for outward normals
if d.volume < 0:
    d.invert()
print("device mesh:", len(d.faces), "tris, extent mm", np.round(d.extents, 1))
d.export(os.path.join(OUT, "Case_001_device.stl"))
with open(os.path.join(OUT, "Case_001_device.stl"), "r+b") as fh:
    fh.write(b"3D Slicer output. SPACE=RAS".ljust(80, b" "))

# ---- 2/3. surface and volume meshes ----
D = os.path.join(ROOT, "data", "derived")
s = np.load(f"{D}/LA_surface_Zaligned_mm_indexed.npz")
surf = trimesh.Trimesh(s["V"], s["F"], process=False)
surf.export(os.path.join(OUT, "Case_001_LA_surface.stl"), file_type="stl_ascii")
shutil.copy(f"{D}/LA_Case001_volume_v1.bdf", os.path.join(OUT, "Case_001_LA_volume.bdf"))
print("written to", OUT)
for fn in sorted(os.listdir(OUT)):
    print(f"  {fn:28s} {os.path.getsize(os.path.join(OUT, fn)) / 1e6:7.2f} MB")
